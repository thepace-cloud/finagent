"""V5-M4b 查询同义扩展 —— 已证伪的检索实验（负结果留档，未上线）

假设：g05/g15 红题的根因是「查询词与文档词零重叠」的词面盲区——
g15 问"年龄"、文档写「18 周岁至 60 周岁」；g05 问"优惠"、anju 写「下浮」。
做法：命中表内词时把同义词拼进检索查询（生成 prompt 不动，只影响召回）。

闸门结果（10-02 全量重跑，v3_eval 第三模式 hybrid+expand）：
  13/16 与 hybrid 持平——g05/g15 没翻绿，也没翻红。

控制实验（假设被证伪的关键一步）：
  - xingwang_loan_0 原文是「借款人年龄在 18 周岁至 60 周岁之间」——
    「年龄」词面本来就有重叠，初始归因就错了。真实根因是查询稀释：
    三产品比较句的大词量把年龄/周岁两个 bigram 摊薄，单索引排序救不回
    （与 g03 同病）。线上真实对比问法走 detect_compare → 分产品子索引，
    不经过这条单索引路径——评测量的是一条生产路由不会走的路。
  - 真实用户问法（带产品锚词）plain 与 expand 的 top-3 完全一致，
    行为零增益。

处置：线上接线已回滚（v5_app.py 墓碑注释）。本模块与评测第三模式保留——
每次跑 v3_eval 都会复述这个假设被证伪的过程，是「假设→闸门→证伪→
回滚→根因修正」的完整审计链。详见 docs/原理卡.md #8。
"""

SYNONYMS = {
    "年龄": "周岁",   # g15；compare 探针「哪个年龄限制更宽松」同病
    "优惠": "下浮",   # g05
}


def expand(query: str) -> str:
    """命中表内词且扩展词尚未出现时，把同义词拼进查询尾部。

    只在检索调用处包一层——生成 prompt 仍用用户原话（回答措辞不被污染，
    扩展只影响召回，不影响表述）。无命中返回原串，零成本退化。
    """
    adds = [syn for key, syn in SYNONYMS.items()
            if key in query and syn not in query]
    return query + (" " + " ".join(adds) if adds else "")
